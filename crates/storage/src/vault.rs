//! The encrypted vault: managed key bodies, shared passwords, the host
//! references that use them and the accepted server identities, sealed in one
//! authenticated ciphertext (R2, R9, ADR-2, ADR-5, ADR-6).
//!
//! The vault is one JSON document, `vault.json`, whose entire body is sealed
//! with AES-256-GCM under a data key (DEK) drawn from the system random source.
//! The DEK itself never appears in the clear: it is sealed again, once for
//! every way the vault may be opened (a *wrap*), and the wraps are the only
//! key material the file holds:
//!
//! * [`UnsealSource::LocalMachine`] — a random local unseal secret that exists
//!   only in the system credential store of this machine. It is generated by
//!   the application, never shown, copied or exported; a user who sets no
//!   password at all still gets an encrypted vault.
//! * [`UnsealSource::WebDavPassword`] — the WebDAV account password, deriving a
//!   key-encryption key (KEK) with Argon2id and wrapping the DEK with it, so a
//!   configured WebDAV password needs no second sync passphrase.
//! * [`UnsealSource::SyncPassphrase`] — a non-empty sync passphrase, required
//!   for passwordless WebDAV and shared with the local export.
//!
//! A local export is the same ciphertext as a [`VaultCipher`] block inside a
//! version 2 portable document (see [`crate::portable`]), sealed under the sync
//! passphrase alone and independent of any WebDAV password.
//!
//! The record kind, the wrap kind and its purpose, the vault identity and the
//! format version are all bound into the authentication data, so a block
//! cannot be lifted into another vault or another kind of document and opened
//! there. A fresh data key, salt and nonce are drawn for every sealing, so the
//! same content sealed twice shares no ciphertext.
//!
//! Saving never endangers the last good file: the content is validated against
//! the host book first (the core [`VaultCatalog`] checks plus the rule that a
//! reference only travels with the sign-in method that reads it), the previous
//! ciphertext is copied aside as an encrypted snapshot, and the new file is
//! written by the same temporary-file-then-rename dance the other stores use.
//! A wrong passphrase, a changed ciphertext, an empty passphrase and a failing
//! system credential store all fail before anything is replaced.
//!
//! [`VaultCatalog`]: shellune_core::VaultCatalog

